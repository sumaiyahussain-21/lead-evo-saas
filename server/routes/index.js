import { Router } from "express";
import authRoutes from "./auth.routes.js";
import leadsRoutes from "./leads.routes.js";
import meetingsRoutes from "./meetings.routes.js";
import seoRoutes from "./seo.routes.js";
import analyticsRoutes from "./analytics.routes.js";
import dbRoutes from "./db.routes.js";
import { AuthController } from "../controllers/auth.controller.js";
import { LeadsController } from "../controllers/leads.controller.js";
const apiRouter = Router();
apiRouter.use("/auth", authRoutes);
apiRouter.put("/user/profile", AuthController.updateProfile);
apiRouter.use("/leads", leadsRoutes);
apiRouter.post("/prospects/discover", LeadsController.discoverProspects);
apiRouter.use("/meetings", meetingsRoutes);
apiRouter.use("/seo", seoRoutes);
apiRouter.use("/analytics", analyticsRoutes);
apiRouter.use("/db", dbRoutes);
export default apiRouter;
